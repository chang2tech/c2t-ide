// IDE-CODE (ext-global-ignore, P1): sync of the `ide.general.globalCursorIgnoreList`
// setting to the engine's codebase index.
//
// Cursor parity: `cursor.general.globalCursorIgnoreList` (REA evidence:
// dig-ast-ext-2026-10-19 §3, deep-env-config.md, parity-settings.md,
// contributes-migration-source.json) — a global ignore list applied to
// indexing/retrieval, separate from the per-project `.cursorignore`. The
// engine (bun sidecar) cannot read the workbench configuration service, so
// the workbench mirrors the setting into `<workspace>/.ide-code/global-ignore`
// (one glob per line), which the engine's `indexing/ignore.ts` merges with
// the highest precedence ("always ignore"). The file is rewritten whenever
// the setting changes; the engine picks it up via mtime-checked refresh
// (watcher), on rescan, and fresh at every query (retrieval filtering).

import * as fs from 'node:fs';
import * as path from 'node:path';

/** The single canonical setting key (mirrors `cursor.general.globalCursorIgnoreList`). */
export const GLOBAL_IGNORE_SETTING_KEY = 'ide.general.globalCursorIgnoreList';

/**
 * Workspace-relative location of the synced file. This exact path is a
 * cross-process contract with the engine — see
 * `packages/core/src/indexing/ignore.ts` (`GLOBAL_IGNORE_REL`).
 */
export const GLOBAL_IGNORE_FILE_RELATIVE = '.ide-code/global-ignore';

export function globalIgnoreFilePath(workspaceFsPath: string): string {
	return path.join(workspaceFsPath, '.ide-code', 'global-ignore');
}

/**
 * Build the file content: a machine-generated header plus one glob pattern
 * per line. Blank entries are dropped (the engine skips blanks/`#` comments
 * itself, but keeping the file clean avoids pointless mtime churn).
 */
export function buildGlobalIgnoreFileContent(patterns: readonly string[]): string {
	const lines = [
		'# Generated by IDE Code from the `ide.general.globalCursorIgnoreList` setting.',
		'# Do not edit by hand: it is rewritten whenever the setting changes.',
	];
	for (const pattern of patterns) {
		const trimmed = pattern.trim();
		if (trimmed.length > 0) {
			lines.push(trimmed);
		}
	}
	return lines.join('\n') + '\n';
}

/**
 * Write the global-ignore file for one workspace root. Skips the write when
 * the content is unchanged so the engine's mtime-checked watcher refresh
 * does not fire needlessly. Never throws — returns 'skipped' on any I/O
 * failure (indexing simply runs without the global list, as before).
 */
export function syncGlobalIgnoreFile(workspaceFsPath: string, patterns: readonly string[]): 'written' | 'unchanged' | 'skipped' {
	try {
		const file = globalIgnoreFilePath(workspaceFsPath);
		const content = buildGlobalIgnoreFileContent(patterns);
		let existing: string | undefined;
		try {
			existing = fs.readFileSync(file, 'utf8');
		} catch {
			existing = undefined;
		}
		if (existing === content) {
			return 'unchanged';
		}
		fs.mkdirSync(path.dirname(file), { recursive: true });
		fs.writeFileSync(file, content);
		return 'written';
	} catch {
		return 'skipped';
	}
}
