// ext-global-ignore (P1, WORKER-GAPS-22E): tests for the workbench → engine
// sync of `ide.general.globalCursorIgnoreList` (mirrors
// `cursor.general.globalCursorIgnoreList`) into
// `<workspace>/.ide-code/global-ignore`.
//
// Covers: setting-key constant (regression guard — the key must stay the
// evidenced mirror), file path contract with the engine, file content
// format, and write/skip behavior of the sync.

import assert from 'assert';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import {
	GLOBAL_IGNORE_FILE_RELATIVE,
	GLOBAL_IGNORE_SETTING_KEY,
	buildGlobalIgnoreFileContent,
	globalIgnoreFilePath,
	syncGlobalIgnoreFile,
} from '../../electron-browser/globalIgnoreSync.js';

function makeTempDir(): string {
	return fs.mkdtempSync(path.join(os.tmpdir(), 'ide-global-ignore-test-'));
}

suite('globalIgnoreSync', () => {

	test('setting key mirrors cursor.general.globalCursorIgnoreList', () => {
		// Regression guard: DEV-GAPS-14 invented `ide.indexing.globalIgnore`;
		// the REA evidence identifies the canonical key — do not rename.
		assert.strictEqual(GLOBAL_IGNORE_SETTING_KEY, 'ide.general.globalCursorIgnoreList');
	});

	test('sync file path matches the engine contract', () => {
		assert.strictEqual(GLOBAL_IGNORE_FILE_RELATIVE, '.ide-code/global-ignore');
		const dir = makeTempDir();
		assert.strictEqual(
			globalIgnoreFilePath(dir),
			path.join(dir, '.ide-code', 'global-ignore')
		);
		fs.rmSync(dir, { recursive: true, force: true });
	});

	test('buildGlobalIgnoreFileContent emits header plus one pattern per line', () => {
		const content = buildGlobalIgnoreFileContent(['*.log', '', '  vendor/  ', '# keep me']);
		const lines = content.split('\n');
		assert.ok(lines[0].startsWith('# Generated by IDE Code'));
		assert.ok(lines[1].startsWith('# Do not edit'));
		assert.deepStrictEqual(lines.slice(2), ['*.log', 'vendor/', '# keep me', '']);
	});

	test('syncGlobalIgnoreFile writes, then reports unchanged when content matches', () => {
		const dir = makeTempDir();
		const patterns = ['*.secret', 'dist/'];
		assert.strictEqual(syncGlobalIgnoreFile(dir, patterns), 'written');
		const file = globalIgnoreFilePath(dir);
		assert.ok(fs.existsSync(file), 'sync file exists');
		assert.strictEqual(fs.readFileSync(file, 'utf8'), buildGlobalIgnoreFileContent(patterns));
		assert.strictEqual(syncGlobalIgnoreFile(dir, patterns), 'unchanged');
		// A settings change rewrites the file.
		assert.strictEqual(syncGlobalIgnoreFile(dir, ['*.secret']), 'written');
		assert.ok(fs.readFileSync(file, 'utf8').includes('dist/') === false);
		fs.rmSync(dir, { recursive: true, force: true });
	});

	test('syncGlobalIgnoreFile creates the .ide-code directory when missing', () => {
		const dir = makeTempDir();
		assert.ok(!fs.existsSync(path.join(dir, '.ide-code')));
		assert.strictEqual(syncGlobalIgnoreFile(dir, []), 'written');
		assert.ok(fs.existsSync(globalIgnoreFilePath(dir)));
		fs.rmSync(dir, { recursive: true, force: true });
	});
});
